import { test, expect } from "@playwright/test"

test("grid cells create one item with Enter or Space", async ({ page }) => {
  await page.goto("./#grid")
  const cells = page.getByRole("button", { name: /^Create item at row \d+, column \d+$/ })
  await expect(cells.first()).toBeVisible()
  const nodes = page.locator("[data-node-id]")
  const initial = await nodes.count()
  await cells.first().focus()
  await expect(cells.first()).toBeFocused()
  await page.keyboard.press("Enter")
  await expect(nodes).toHaveCount(initial + 1)
  await cells.last().focus()
  await expect(cells.last()).toBeFocused()
  await page.keyboard.press("Space")
  await expect(nodes).toHaveCount(initial + 2)
})

test("grid pointer creation keeps single-click, double-click and drag behavior", async ({ page }) => {
  await page.goto("./#grid")
  const cells = page.getByRole("button", { name: /^Create item at row \d+, column \d+$/ })
  const nodes = page.locator("[data-node-id]")
  await expect(cells.last()).toBeVisible()
  const initial = await nodes.count()
  await cells.last().click()
  await expect(nodes).toHaveCount(initial)
  await cells.last().dblclick()
  await expect(nodes).toHaveCount(initial + 1)
  await page.reload()
  await expect(cells.first()).toBeVisible()
  const beforeDrag = await nodes.count()
  const start = await cells.nth(0).boundingBox()
  const end = await cells.nth(1).boundingBox()
  if (!start || !end) throw new Error("Grid cells have no pointer bounds")
  await page.mouse.move(start.x + start.width / 2, start.y + start.height / 2)
  await page.mouse.down()
  await page.mouse.move(end.x + end.width / 2, end.y + end.height / 2, { steps: 5 })
  await page.mouse.up()
  await expect(nodes).toHaveCount(beforeDrag + 1)
})
